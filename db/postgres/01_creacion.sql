\set ON_ERROR_STOP on

DROP SCHEMA IF EXISTS sirav CASCADE;
CREATE SCHEMA sirav;
SET search_path TO sirav, public;

-- Necesaria para la restricción de exclusión RN-01 (vehículo + rango de fechas)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- =====================================================================
-- 1. ACCESOS Y PERSONAS
-- =====================================================================

CREATE TABLE usuario (
  id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre         VARCHAR(100) NOT NULL,
  apellido       VARCHAR(100) NOT NULL,
  email          VARCHAR(150) NOT NULL,
  password_hash  VARCHAR(255) NOT NULL,
  activo         BOOLEAN      NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuario_email UNIQUE (email),
  CONSTRAINT ck_usuario_email CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

CREATE TABLE rol (
  id_rol  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre  VARCHAR(30) NOT NULL,
  CONSTRAINT pk_rol PRIMARY KEY (id_rol),
  CONSTRAINT uq_rol_nombre UNIQUE (nombre),
  CONSTRAINT ck_rol_nombre CHECK (nombre IN ('ADMINISTRADOR', 'OPERADOR', 'CLIENTE'))
);

-- N:M usuario-rol (especialización superpuesta del EER)
CREATE TABLE usuario_rol (
  id_usuario   BIGINT      NOT NULL,
  id_rol       BIGINT      NOT NULL,
  asignado_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol),
  CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol)
    REFERENCES rol (id_rol)
);

-- 1:1 opcional con usuario (un cliente puede no tener cuenta web)
CREATE TABLE cliente (
  id_cliente           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_usuario           BIGINT,
  nombres              VARCHAR(100) NOT NULL,
  apellidos            VARCHAR(100) NOT NULL,
  documento            VARCHAR(30)  NOT NULL,
  telefono             VARCHAR(25),
  email                VARCHAR(150),
  licencia_conduccion  VARCHAR(40),
  CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
  CONSTRAINT uq_cliente_id_usuario UNIQUE (id_usuario),
  CONSTRAINT uq_cliente_documento UNIQUE (documento),
  CONSTRAINT fk_cliente_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE SET NULL,
  CONSTRAINT ck_cliente_email CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

-- =====================================================================
-- 2. FLOTA, TARIFAS Y SERVICIOS
-- =====================================================================

CREATE TABLE categoria_vehiculo (
  id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre        VARCHAR(70) NOT NULL,
  descripcion   TEXT,
  CONSTRAINT pk_categoria_vehiculo PRIMARY KEY (id_categoria),
  CONSTRAINT uq_categoria_vehiculo_nombre UNIQUE (nombre)
);

CREATE TABLE vehiculo (
  id_vehiculo         BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_categoria        BIGINT      NOT NULL,
  placa               VARCHAR(12) NOT NULL,
  marca               VARCHAR(70) NOT NULL,
  modelo              VARCHAR(70) NOT NULL,
  anio                SMALLINT    NOT NULL,
  color               VARCHAR(40),
  kilometraje_actual  INTEGER     NOT NULL DEFAULT 0,
  estado_operativo    VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
  CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
  CONSTRAINT uq_vehiculo_placa UNIQUE (placa),
  CONSTRAINT fk_vehiculo_categoria FOREIGN KEY (id_categoria)
    REFERENCES categoria_vehiculo (id_categoria),
  CONSTRAINT ck_vehiculo_anio CHECK (anio BETWEEN 1990 AND 2100),
  CONSTRAINT ck_vehiculo_km CHECK (kilometraje_actual >= 0),
  CONSTRAINT ck_vehiculo_estado CHECK (estado_operativo IN
    ('DISPONIBLE', 'RESERVADO', 'ENTREGADO', 'MANTENIMIENTO', 'INACTIVO'))
);

CREATE TABLE tarifa (
  id_tarifa      BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_categoria   BIGINT        NOT NULL,
  valor_diario   NUMERIC(12,2) NOT NULL,
  vigente_desde  DATE          NOT NULL,
  vigente_hasta  DATE,
  CONSTRAINT pk_tarifa PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_tarifa_categoria FOREIGN KEY (id_categoria)
    REFERENCES categoria_vehiculo (id_categoria),
  CONSTRAINT ck_tarifa_valor CHECK (valor_diario > 0),
  CONSTRAINT ck_tarifa_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
  -- Una categoría no puede tener dos tarifas vigentes al mismo tiempo
  CONSTRAINT ex_tarifa_vigencia_solapada EXCLUDE USING gist (
    id_categoria WITH =,
    daterange(vigente_desde, vigente_hasta, '[]') WITH &&
  )
);

CREATE TABLE mantenimiento (
  id_mantenimiento  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_vehiculo       BIGINT      NOT NULL,
  fecha_inicio      DATE        NOT NULL,
  fecha_fin         DATE        NOT NULL,
  descripcion       TEXT        NOT NULL,
  estado            VARCHAR(15) NOT NULL DEFAULT 'PROGRAMADO',
  CONSTRAINT pk_mantenimiento PRIMARY KEY (id_mantenimiento),
  CONSTRAINT fk_mantenimiento_vehiculo FOREIGN KEY (id_vehiculo)
    REFERENCES vehiculo (id_vehiculo),
  CONSTRAINT ck_mantenimiento_fechas CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_mantenimiento_estado CHECK (estado IN
    ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO'))
);

-- =====================================================================
-- 3. OPERACIÓN Y TRAZABILIDAD
-- =====================================================================

CREATE TABLE reserva (
  id_reserva       BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_cliente       BIGINT      NOT NULL,
  id_vehiculo      BIGINT      NOT NULL,
  id_tarifa        BIGINT      NOT NULL,
  fecha_inicio     DATE        NOT NULL,
  fecha_fin        DATE        NOT NULL,
  fecha_solicitud  TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado           VARCHAR(15) NOT NULL DEFAULT 'SOLICITADA',
  CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
  CONSTRAINT fk_reserva_cliente FOREIGN KEY (id_cliente)
    REFERENCES cliente (id_cliente),
  CONSTRAINT fk_reserva_vehiculo FOREIGN KEY (id_vehiculo)
    REFERENCES vehiculo (id_vehiculo),
  CONSTRAINT fk_reserva_tarifa FOREIGN KEY (id_tarifa)
    REFERENCES tarifa (id_tarifa),
  CONSTRAINT ck_reserva_fechas CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_reserva_estado CHECK (estado IN
    ('SOLICITADA', 'CONFIRMADA', 'ACTIVA', 'CERRADA', 'CANCELADA')),
  -- El orden de las transiciones (RN-03) lo valida trg_validar_transicion_reserva
  -- RN-01: un vehículo no puede tener dos reservas SOLICITADA, CONFIRMADA o
  -- ACTIVA con periodos solapados. CERRADA y CANCELADA no bloquean. (SIRAV-18)
  CONSTRAINT ex_reserva_solapada EXCLUDE USING gist (
    id_vehiculo WITH =,
    daterange(fecha_inicio, fecha_fin, '[]') WITH &&
  ) WHERE (estado IN ('SOLICITADA', 'CONFIRMADA', 'ACTIVA'))
);

-- 1:1 con reserva (UNIQUE en la FK)
CREATE TABLE alquiler (
  id_alquiler          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_reserva           BIGINT       NOT NULL,
  fecha_entrega        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  fecha_devolucion     TIMESTAMPTZ,
  km_salida            INTEGER      NOT NULL,
  km_entrada           INTEGER,
  combustible_salida   NUMERIC(5,2) NOT NULL,
  combustible_entrada  NUMERIC(5,2),
  estado               VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
  CONSTRAINT pk_alquiler PRIMARY KEY (id_alquiler),
  CONSTRAINT uq_alquiler_id_reserva UNIQUE (id_reserva),
  CONSTRAINT fk_alquiler_reserva FOREIGN KEY (id_reserva)
    REFERENCES reserva (id_reserva),
  CONSTRAINT ck_alquiler_km CHECK (km_salida >= 0 AND (km_entrada IS NULL OR km_entrada >= km_salida)),
  CONSTRAINT ck_alquiler_combustible CHECK (
    combustible_salida BETWEEN 0 AND 100 AND
    (combustible_entrada IS NULL OR combustible_entrada BETWEEN 0 AND 100)),
  CONSTRAINT ck_alquiler_fechas CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_entrega),
  CONSTRAINT ck_alquiler_estado CHECK (estado IN ('ACTIVO', 'CERRADO')),
  -- RN-05 (parte relacional): un alquiler cerrado debe tener los datos de
  -- devolución. La inspección en MongoDB la verifica sp_cerrar_alquiler.
  CONSTRAINT ck_alquiler_cierre CHECK (estado <> 'CERRADO' OR
    (fecha_devolucion IS NOT NULL AND km_entrada IS NOT NULL AND combustible_entrada IS NOT NULL))
);

CREATE TABLE pago (
  id_pago      BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_alquiler  BIGINT        NOT NULL,
  fecha_pago   TIMESTAMPTZ   NOT NULL DEFAULT now(),
  monto        NUMERIC(12,2) NOT NULL,
  tipo         VARCHAR(30)   NOT NULL,
  estado       VARCHAR(15)   NOT NULL DEFAULT 'PENDIENTE',
  CONSTRAINT pk_pago PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_alquiler FOREIGN KEY (id_alquiler)
    REFERENCES alquiler (id_alquiler),
  CONSTRAINT ck_pago_monto CHECK (monto > 0),
  CONSTRAINT ck_pago_tipo CHECK (tipo IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'PRUEBA')),
  CONSTRAINT ck_pago_estado CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ANULADO'))
);

CREATE TABLE cargo_adicional (
  id_cargo        BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_alquiler     BIGINT        NOT NULL,
  concepto        VARCHAR(60)   NOT NULL,
  descripcion     TEXT,
  monto           NUMERIC(12,2) NOT NULL,
  fecha_registro  TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT pk_cargo_adicional PRIMARY KEY (id_cargo),
  CONSTRAINT fk_cargo_adicional_alquiler FOREIGN KEY (id_alquiler)
    REFERENCES alquiler (id_alquiler),
  CONSTRAINT ck_cargo_monto CHECK (monto > 0),
  CONSTRAINT ck_cargo_concepto CHECK (concepto IN
    ('RETRASO', 'COMBUSTIBLE', 'DANO', 'LIMPIEZA', 'KILOMETRAJE', 'OTRO'))
);

CREATE TABLE auditoria_reserva (
  id_auditoria     BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_reserva       BIGINT      NOT NULL,
  id_usuario       BIGINT,
  estado_anterior  VARCHAR(15),
  estado_nuevo     VARCHAR(15) NOT NULL,
  fecha_evento     TIMESTAMPTZ NOT NULL DEFAULT now(),
  observacion      TEXT,
  CONSTRAINT pk_auditoria_reserva PRIMARY KEY (id_auditoria),
  CONSTRAINT fk_auditoria_reserva_reserva FOREIGN KEY (id_reserva)
    REFERENCES reserva (id_reserva),
  CONSTRAINT fk_auditoria_reserva_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

-- =====================================================================
-- 4. ÍNDICES (las FK no se indexan solas en PostgreSQL)
-- =====================================================================

-- Consultas de disponibilidad por vehículo y fechas (fn_vehiculo_disponible)
CREATE INDEX ix_reserva_vehiculo_fechas   ON reserva (id_vehiculo, fecha_inicio, fecha_fin);
CREATE INDEX ix_reserva_cliente           ON reserva (id_cliente);
CREATE INDEX ix_reserva_tarifa            ON reserva (id_tarifa);
CREATE INDEX ix_reserva_estado            ON reserva (estado);

CREATE INDEX ix_vehiculo_categoria_estado ON vehiculo (id_categoria, estado_operativo);
CREATE INDEX ix_tarifa_categoria_vigencia ON tarifa (id_categoria, vigente_desde);
CREATE INDEX ix_mantenimiento_vehiculo_fechas ON mantenimiento (id_vehiculo, fecha_inicio, fecha_fin);

CREATE INDEX ix_alquiler_estado           ON alquiler (estado);
CREATE INDEX ix_pago_alquiler             ON pago (id_alquiler);
CREATE INDEX ix_cargo_adicional_alquiler  ON cargo_adicional (id_alquiler);

CREATE INDEX ix_auditoria_reserva_reserva ON auditoria_reserva (id_reserva, fecha_evento);
CREATE INDEX ix_auditoria_reserva_usuario ON auditoria_reserva (id_usuario);
CREATE INDEX ix_usuario_rol_rol           ON usuario_rol (id_rol);

