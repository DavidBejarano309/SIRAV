CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. USUARIO: fuente de identidad para personas con cuenta.
CREATE TABLE USUARIO (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(100) NOT NULL,
  apellido VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  token_version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT pk_USUARIO PRIMARY KEY (id_usuario),
  CONSTRAINT uq_USUARIO_email UNIQUE (email),
  CONSTRAINT ck_USUARIO_token_version CHECK (token_version >= 0)
);

-- 2. ROL: cada atributo depende de la clave id_rol.
CREATE TABLE ROL (
  id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(30) NOT NULL,
  CONSTRAINT pk_ROL PRIMARY KEY (id_rol),
  CONSTRAINT uq_ROL_nombre UNIQUE (nombre)
);

-- 3. USUARIO_ROL: atributo asignado_en depende del par completo (usuario, rol).
CREATE TABLE USUARIO_ROL (
  id_usuario BIGINT NOT NULL,
  id_rol BIGINT NOT NULL,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_USUARIO_ROL PRIMARY KEY (id_usuario, id_rol),
  CONSTRAINT fk_USUARIO_ROL_id_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO (id_usuario),
  CONSTRAINT fk_USUARIO_ROL_id_rol FOREIGN KEY (id_rol) REFERENCES ROL (id_rol)
);

-- 4. CLIENTE: se permite registrar clientes SIN cuenta de acceso.
-- Si id_usuario ES NULL: nombres/apellidos obligatorios, email opcional.
-- Si id_usuario NO ES NULL: identidad se consulta en USUARIO;
--     los campos nombres, apellidos y email en CLIENTE deben ser NULL.
-- La restriccion evita anomalias de actualizacion de datos duplicados.
CREATE TABLE CLIENTE (
  id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_usuario BIGINT,
  nombres VARCHAR(100),
  apellidos VARCHAR(100),
  documento VARCHAR(30) NOT NULL,
  telefono VARCHAR(25),
  email VARCHAR(150),
  licencia_conduccion VARCHAR(40),
  CONSTRAINT pk_CLIENTE PRIMARY KEY (id_cliente),
  CONSTRAINT uq_CLIENTE_id_usuario UNIQUE (id_usuario),
  CONSTRAINT uq_CLIENTE_documento UNIQUE (documento),
  CONSTRAINT fk_CLIENTE_id_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO (id_usuario),
  CONSTRAINT ck_CLIENTE_origen_identidad CHECK (
    (id_usuario IS NULL
       AND NULLIF(BTRIM(nombres), '') IS NOT NULL
       AND NULLIF(BTRIM(apellidos), '') IS NOT NULL)
    OR
    (id_usuario IS NOT NULL
       AND nombres IS NULL
       AND apellidos IS NULL
       AND email IS NULL)
  )
);

-- 5. CATEGORIA_VEHICULO.
CREATE TABLE CATEGORIA_VEHICULO (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(70) NOT NULL,
  descripcion VARCHAR(4000),
  CONSTRAINT pk_CATEGORIA_VEHICULO PRIMARY KEY (id_categoria),
  CONSTRAINT uq_CATEGORIA_VEHICULO_nombre UNIQUE (nombre)
);

-- 6. VEHICULO: solo id_categoria; evita copiar nombre de categoria.
CREATE TABLE VEHICULO (
  id_vehiculo BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_categoria BIGINT NOT NULL,
  placa VARCHAR(12) NOT NULL,
  marca VARCHAR(70) NOT NULL,
  modelo VARCHAR(70) NOT NULL,
  anio SMALLINT NOT NULL,
  color VARCHAR(40),
  kilometraje_actual INTEGER NOT NULL,
  estado_operativo VARCHAR(20) NOT NULL,
  CONSTRAINT pk_VEHICULO PRIMARY KEY (id_vehiculo),
  CONSTRAINT uq_VEHICULO_placa UNIQUE (placa),
  CONSTRAINT fk_VEHICULO_id_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIA_VEHICULO (id_categoria),
  CONSTRAINT ck_VEHICULO_km CHECK (kilometraje_actual >= 0)
);

-- 7. TARIFA: las tarifas son historicas por categoria; no copiar valor en VEHICULO.
CREATE TABLE TARIFA (
  id_tarifa BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_categoria BIGINT NOT NULL,
  valor_diario NUMERIC(12,2) NOT NULL,
  vigente_desde DATE NOT NULL,
  vigente_hasta DATE,
  CONSTRAINT pk_TARIFA PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_TARIFA_id_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIA_VEHICULO (id_categoria),
  CONSTRAINT ck_TARIFA_valor CHECK (valor_diario > 0),
  CONSTRAINT ck_TARIFA_fechas CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

-- 8. RESERVA: cliente, vehiculo y tarifa se referencian por FK.
-- La tarifa debe pertenecer a la categoria del vehiculo en la fecha de reserva;
-- esa regla ENTRE TABLAS debe verificarse con procedimiento/trigger.
CREATE TABLE RESERVA (
  id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_cliente BIGINT NOT NULL,
  id_vehiculo BIGINT NOT NULL,
  id_tarifa BIGINT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado VARCHAR(15) NOT NULL,
  CONSTRAINT pk_RESERVA PRIMARY KEY (id_reserva),
  CONSTRAINT fk_RESERVA_id_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE (id_cliente),
  CONSTRAINT fk_RESERVA_id_vehiculo FOREIGN KEY (id_vehiculo) REFERENCES VEHICULO (id_vehiculo),
  CONSTRAINT fk_RESERVA_id_tarifa FOREIGN KEY (id_tarifa) REFERENCES TARIFA (id_tarifa),
  CONSTRAINT ck_RESERVA_fechas CHECK (fecha_fin > fecha_inicio)
);

-- Regla de NEGOCIO, no de normalizacion: impide solapamientos.
-- Fechas interpretadas como intervalo [inicio, fin): salida en fecha_fin.
ALTER TABLE RESERVA
  ADD CONSTRAINT ex_RESERVA_vehiculo_periodo
  EXCLUDE USING gist (
    id_vehiculo WITH =,
    daterange(fecha_inicio, fecha_fin, '[)') WITH &&
  )
  WHERE (estado IN ('SOLICITADA', 'CONFIRMADA', 'ACTIVA'));

-- 9. ALQUILER: relacion 1:1 con RESERVA mediante UNIQUE(id_reserva).
CREATE TABLE ALQUILER (
  id_alquiler BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_reserva BIGINT NOT NULL,
  fecha_entrega TIMESTAMPTZ NOT NULL,
  fecha_devolucion TIMESTAMPTZ,
  km_salida INTEGER NOT NULL,
  km_entrada INTEGER,
  combustible_salida NUMERIC(5,2) NOT NULL,
  combustible_entrada NUMERIC(5,2),
  estado VARCHAR(15) NOT NULL,
  CONSTRAINT pk_ALQUILER PRIMARY KEY (id_alquiler),
  CONSTRAINT uq_ALQUILER_id_reserva UNIQUE (id_reserva),
  CONSTRAINT fk_ALQUILER_id_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA (id_reserva),
  CONSTRAINT ck_ALQUILER_km CHECK (km_salida >= 0 AND (km_entrada IS NULL OR km_entrada >= km_salida)),
  CONSTRAINT ck_ALQUILER_fechas CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_entrega)
);

-- 10. PAGO: no replica nombre de cliente ni atributos de reserva.
CREATE TABLE PAGO (
  id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_alquiler BIGINT NOT NULL,
  fecha_pago TIMESTAMPTZ NOT NULL DEFAULT now(),
  monto NUMERIC(12,2) NOT NULL,
  tipo VARCHAR(30) NOT NULL,
  estado VARCHAR(15) NOT NULL,
  CONSTRAINT pk_PAGO PRIMARY KEY (id_pago),
  CONSTRAINT fk_PAGO_id_alquiler FOREIGN KEY (id_alquiler) REFERENCES ALQUILER (id_alquiler),
  CONSTRAINT ck_PAGO_monto CHECK (monto >= 0)
);

-- 11. CARGO_ADICIONAL.
CREATE TABLE CARGO_ADICIONAL (
  id_cargo BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_alquiler BIGINT NOT NULL,
  concepto VARCHAR(60) NOT NULL,
  descripcion VARCHAR(4000),
  monto NUMERIC(12,2) NOT NULL,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_CARGO_ADICIONAL PRIMARY KEY (id_cargo),
  CONSTRAINT fk_CARGO_ADICIONAL_id_alquiler FOREIGN KEY (id_alquiler) REFERENCES ALQUILER (id_alquiler),
  CONSTRAINT ck_CARGO_ADICIONAL_monto CHECK (monto >= 0)
);

-- 12. MANTENIMIENTO.
CREATE TABLE MANTENIMIENTO (
  id_mantenimiento BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_vehiculo BIGINT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  descripcion VARCHAR(4000) NOT NULL,
  estado VARCHAR(15) NOT NULL,
  CONSTRAINT pk_MANTENIMIENTO PRIMARY KEY (id_mantenimiento),
  CONSTRAINT fk_MANTENIMIENTO_id_vehiculo FOREIGN KEY (id_vehiculo) REFERENCES VEHICULO (id_vehiculo),
  CONSTRAINT ck_MANTENIMIENTO_fechas CHECK (fecha_fin > fecha_inicio)
);

-- 13. AUDITORIA_RESERVA: cada evento tiene identidad propia.
CREATE TABLE AUDITORIA_RESERVA (
  id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_reserva BIGINT NOT NULL,
  id_usuario BIGINT,
  estado_anterior VARCHAR(15),
  estado_nuevo VARCHAR(15) NOT NULL,
  fecha_evento TIMESTAMPTZ NOT NULL DEFAULT now(),
  observacion VARCHAR(4000),
  CONSTRAINT pk_AUDITORIA_RESERVA PRIMARY KEY (id_auditoria),
  CONSTRAINT fk_AUDITORIA_RESERVA_id_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA (id_reserva),
  CONSTRAINT fk_AUDITORIA_RESERVA_id_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO (id_usuario)
);

-- Vista auxiliar (NO es una tabla ni una 14a entidad de dominio).
-- Recupera la identidad de clientes tanto con cuenta como sin cuenta.
CREATE VIEW v_cliente_contacto AS
SELECT
  c.id_cliente,
  c.id_usuario,
  COALESCE(u.nombre, c.nombres) AS nombres,
  COALESCE(u.apellido, c.apellidos) AS apellidos,
  c.documento,
  c.telefono,
  COALESCE(u.email, c.email) AS email,
  c.licencia_conduccion
FROM CLIENTE c
LEFT JOIN USUARIO u ON u.id_usuario = c.id_usuario;

